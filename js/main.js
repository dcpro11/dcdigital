let currentLang = 'pt';

function setLang(lang){
  currentLang = lang;
  document.documentElement.lang = lang === 'pt' ? 'pt' : 'en';
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined){
      el.textContent = translations[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach(function(el){
    const key = el.getAttribute('data-i18n-html');
    if (key === 'hero_h1'){ el.innerHTML = heroHtml[lang]; }
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el){
    const key = el.getAttribute('data-i18n-aria');
    if (translations[lang] && translations[lang][key] !== undefined){
      el.setAttribute('aria-label', translations[lang][key]);
    }
  });
  document.querySelectorAll('[data-lang-content]').forEach(function(el){
    el.hidden = el.getAttribute('data-lang-content') !== lang;
  });
  document.querySelectorAll('.langswitch button').forEach(function(btn){
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  document.title = lang === 'pt'
    ? 'DC Digital — Soluções digitais para pequenos negócios'
    : 'DC Digital — Digital solutions for small businesses';
}

document.querySelectorAll('.langswitch button').forEach(function(btn){
  btn.addEventListener('click', function(){ setLang(btn.getAttribute('data-lang')); });
});

